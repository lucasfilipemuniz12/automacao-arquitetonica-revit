Check(Near(LegalMetrics.PolygonArea(new[]{(1e9,1e9),(1e9+20,1e9),(1e9+20,1e9+30),(1e9,1e9+30)}),600),"Coordenadas distantes sem perda por cancelamento");
Check(Near(LegalMetrics.Ratio(150,600,true),25),"TO 150 / 600 = 25%");
